-- 0003: procedencia de documentos por buzon (muchos a muchos, clave global y correo por cuenta).
-- objetos: dbo.FE_BUZON_DOC_CUENTAS, dbo.FE_BUZON_DOC_CUENTAS.IX_FE_BUZON_DOC_CUENTA
IF OBJECT_ID('dbo.FE_BUZON_DOC_CUENTAS', 'U') IS NULL
CREATE TABLE dbo.FE_BUZON_DOC_CUENTAS (
    CLAVE varchar(50) NOT NULL,
    CUENTA varchar(120) NOT NULL,
    CORREO_ID int NULL,
    FECHA datetime2(0) NOT NULL CONSTRAINT DF_FE_BUZON_DOC_CUENTA_F DEFAULT SYSDATETIME(),
    CONSTRAINT PK_FE_BUZON_DOC_CUENTAS PRIMARY KEY (CLAVE, CUENTA)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.FE_BUZON_DOC_CUENTAS') AND name = 'IX_FE_BUZON_DOC_CUENTA')
CREATE INDEX IX_FE_BUZON_DOC_CUENTA ON dbo.FE_BUZON_DOC_CUENTAS (CUENTA, CLAVE);
GO
-- Procedencia de los datos anteriores; no se cambian los documentos ni se borra nada.
INSERT INTO dbo.FE_BUZON_DOC_CUENTAS (CLAVE, CUENTA, CORREO_ID)
SELECT x.CLAVE, x.CUENTA, MIN(x.CORREO_ID) FROM (
    SELECT d.CLAVE, c.CUENTA, c.ID CORREO_ID FROM dbo.FE_BUZON_DOCUMENTOS d JOIN dbo.FE_BUZON_CORREOS c ON c.ID = d.CORREO_ID
    UNION ALL SELECT a.CLAVE, c.CUENTA, c.ID FROM dbo.FE_BUZON_ARCHIVOS a JOIN dbo.FE_BUZON_CORREOS c ON c.ID = a.CORREO_ID WHERE a.CLAVE IS NOT NULL
) x WHERE NOT EXISTS (SELECT 1 FROM dbo.FE_BUZON_DOC_CUENTAS p WHERE p.CLAVE = x.CLAVE AND p.CUENTA = x.CUENTA)
GROUP BY x.CLAVE, x.CUENTA;
GO
